/// Synchronous HTTP client for the Velocity Router API.
pub struct VelocityClient {
    config: VelocityConfig,
    agent: ureq::Agent,
    retry_config: RetryConfig,
}

/// Retry configuration for HTTP requests.
#[derive(Debug, Clone)]
pub struct RetryConfig {
    /// Maximum number of retry attempts (not counting the initial request).
    pub max_retries: u32,
    /// Initial backoff duration.
    pub initial_backoff_ms: u64,
    /// Maximum backoff duration.
    pub max_backoff_ms: u64,
    /// Whether to add random jitter to backoff (avoids thundering herd).
    pub jitter: bool,
}

impl Default for RetryConfig {
    fn default() -> Self {
        Self {
            max_retries: 3,
            initial_backoff_ms: 200,
            max_backoff_ms: 5000,
            jitter: true,
        }
    }
}

impl VelocityClient {
    pub fn new(config: VelocityConfig) -> Self {
        let agent = ureq::AgentBuilder::new()
            .timeout_connect(Duration::from_secs(5))
            .timeout_read(Duration::from_secs(30))
            .timeout_write(Duration::from_secs(10))
            .build();
        Self {
            config,
            agent,
            retry_config: RetryConfig::default(),
        }
    }

    pub fn from_env() -> Result<Self> {
        let config = VelocityConfig::load()?;
        Ok(Self::new(config))
    }

    /// Set custom retry configuration.
    pub fn with_retry_config(mut self, config: RetryConfig) -> Self {
        self.retry_config = config;
        self
    }

    fn auth_header(&self) -> String {
        format!("Bearer {}", self.config.api_key)
    }

    fn url(&self, path: &str) -> String {
        format!("{}{}", self.config.base_url.trim_end_matches('/'), path)
    }

    /// Compute backoff duration with optional jitter.
    fn backoff_duration(&self, base_ms: u64) -> Duration {
        let ms = if self.retry_config.jitter {
            // Add ±25% random jitter to avoid thundering herd.
            let jitter_range = base_ms / 4;
            let jitter = if jitter_range > 0 {
                (rand::random::<u64>() % (jitter_range * 2)).saturating_sub(jitter_range)
            } else {
                0
            };
            base_ms.saturating_add_signed(jitter as i64)
        } else {
            base_ms
        };
        Duration::from_millis(ms.min(self.retry_config.max_backoff_ms))
    }

    /// Execute a GET request with exponential backoff retry.
    /// Retries on 5xx errors and transport failures.
    fn get_with_retry(&self, url: &str, auth: bool) -> Result<ureq::Response> {
        let mut last_error = None;
        let mut backoff = self.retry_config.initial_backoff_ms;

        for attempt in 0..=self.retry_config.max_retries {
            let mut req = self.agent.get(url);
            if auth {
                req = req.set("Authorization", &self.auth_header());
            }

            match req.call() {
                Ok(resp) => return Ok(resp),
                Err(ureq::Error::Status(code, _resp)) if code >= 500 => {
                    last_error = Some(anyhow::anyhow!("server error: HTTP {}", code));
                    if attempt < self.retry_config.max_retries {
                        std::thread::sleep(self.backoff_duration(backoff));
                        backoff = (backoff * 2).min(self.retry_config.max_backoff_ms);
                    }
                }
                Err(ureq::Error::Transport(_)) => {
                    last_error = Some(anyhow::anyhow!("transport error (connection failed)"));
                    if attempt < self.retry_config.max_retries {
                        std::thread::sleep(self.backoff_duration(backoff));
                        backoff = (backoff * 2).min(self.retry_config.max_backoff_ms);
                    }
                }
                Err(e) => return Err(anyhow::anyhow!("{}", e)),
            }
        }

        Err(last_error.unwrap_or_else(|| anyhow::anyhow!("max retries exceeded")))
    }

    /// GET /health — check if the router is reachable.
    pub fn health(&self) -> Result<HealthResponse> {
        let resp = self
            .get_with_retry(&self.url("/health"), false)
            .context("failed to reach velocity router")?;
        resp.into_json()
            .context("failed to parse health response")
    }

    /// GET /v1/usage — current usage summary.
    pub fn get_usage(&self) -> Result<UsageResponse> {
        let resp = self
            .get_with_retry(&self.url("/v1/usage"), true)
            .context("failed to fetch usage")?;
        resp.into_json()
            .context("failed to parse usage response")
    }

    /// GET /v1/usage/summary — enhanced usage with projections and sparkline.
    pub fn get_usage_summary(&self) -> Result<UsageSummaryResponse> {
        let resp = self
            .get_with_retry(&self.url("/v1/usage/summary"), true)
            .context("failed to fetch usage summary")?;
        resp.into_json()
            .context("failed to parse usage summary response")
    }

    /// GET /v1/usage/detailed — per-model and per-domain breakdown.
    pub fn get_usage_detailed(&self) -> Result<UsageDetailed> {
        let resp = self
            .get_with_retry(&self.url("/v1/usage/detailed"), true)
            .context("failed to fetch detailed usage")?;
        resp.into_json()
            .context("failed to parse detailed usage response")
    }

    /// GET /v1/usage/rate-limit — rate limit and quota status.
    pub fn get_rate_limit(&self) -> Result<RateLimitResponse> {
        let resp = self
            .get_with_retry(&self.url("/v1/usage/rate-limit"), true)
            .context("failed to fetch rate limit status")?;
        resp.into_json()
            .context("failed to parse rate limit response")
    }

    /// GET /v1/usage/timeseries — time-series usage data.
    /// `granularity`: "hourly" or "daily".
    /// `range`: "6h", "12h", "24h", "48h", "7d", "30d", "90d".
    pub fn get_timeseries(&self, granularity: &str, range: &str) -> Result<TimeseriesResponse> {
        let url = format!(
            "{}/v1/usage/timeseries?granularity={}&range={}",
            self.config.base_url.trim_end_matches('/'),
            granularity,
            range
        );
        let resp = self
            .get_with_retry(&url, true)
            .context("failed to fetch timeseries")?;
        resp.into_json()
            .context("failed to parse timeseries response")
    }

    /// GET /v1/transparency — full routing transparency data.
    pub fn get_transparency(&self) -> Result<TransparencyResponse> {
        let resp = self
            .get_with_retry(&self.url("/v1/transparency"), true)
            .context("failed to fetch transparency data")?;
        resp.into_json()
            .context("failed to parse transparency response")
    }

    /// GET /v1/audit-log — paginated audit trail.
    pub fn get_audit_log(&self) -> Result<AuditLogResponse> {
        let resp = self
            .get_with_retry(&self.url("/v1/audit-log"), true)
            .context("failed to fetch audit log")?;
        resp.into_json()
            .context("failed to parse audit log response")
    }

    /// GET /v1/analytics/latency — latency percentiles.
    pub fn get_latency(&self) -> Result<LatencyResponse> {
        let resp = self
            .get_with_retry(&self.url("/v1/analytics/latency"), true)
            .context("failed to fetch latency analytics")?;
        resp.into_json()
            .context("failed to parse latency response")
    }

    /// GET /admin/keys/:hash — key detail (admin only).
    pub fn get_key_detail(&self, hash: &str) -> Result<KeyDetailResponse> {
        let resp = self
            .get_with_retry(&self.url(&format!("/admin/keys/{}", hash)), true)
            .context("failed to fetch key detail")?;
        resp.into_json()
            .context("failed to parse key detail response")
    }

    /// POST /admin/keys/:hash/rotate — rotate an API key (admin only).
    pub fn rotate_key(&self, hash: &str) -> Result<RotateKeyResponse> {
        let resp = self
            .agent
            .post(&self.url(&format!("/admin/keys/{}/rotate", hash)))
            .set("Authorization", &self.auth_header())
            .call()
            .context("failed to rotate key")?;
        resp.into_json()
            .context("failed to parse rotate key response")
    }

    /// POST /v1/assignments — submit a task for orchestration.
    pub fn submit_assignment(&self, req: &AssignmentRequest) -> Result<AssignmentResponse> {
        let resp = self
            .agent
            .post(&self.url("/v1/assignments"))
            .set("Authorization", &self.auth_header())
            .set("Content-Type", "application/json")
            .send_json(serde_json::to_value(req)?)
            .context("failed to submit assignment")?;
        resp.into_json()
            .context("failed to parse assignment response")
    }

    /// GET /v1/assignments/:id — poll assignment status.
    pub fn get_assignment(&self, id: &str) -> Result<AssignmentResponse> {
        let resp = self
            .get_with_retry(&self.url(&format!("/v1/assignments/{}", id)), true)
            .context("failed to fetch assignment")?;
        resp.into_json()
            .context("failed to parse assignment response")
    }
}

// ─── Formatting Helpers ─────────────────────────────────────────────────

/// Format a number with thousands separators.
pub fn fmt_number(n: u64) -> String {
    let s = n.to_string();
    let mut result = String::new();
    for (i, c) in s.chars().rev().enumerate() {
        if i > 0 && i % 3 == 0 {
            result.push(',');
        }
        result.push(c);
    }
    result.chars().rev().collect()
}

/// Format a USD amount.
pub fn fmt_currency(n: f64) -> String {
    if n == 0.0 {
        "$0.00".to_string()
    } else if n < 0.01 {
        format!("${:.4}", n)
    } else {
        format!("${:.2}", n)
    }
}

/// Format a percentage.
pub fn fmt_percent(n: f64) -> String {
    format!("{:.1}%", n)
}

