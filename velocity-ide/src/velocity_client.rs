//! Velocity Router HTTP client.
//!
//! Provides a typed interface to the Velocity Model Router API for usage
//! tracking, assignment submission, cost monitoring, transparency data,
//! timeseries analytics, audit logs, and API key management.

use std::collections::HashMap;
use std::time::Duration;

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

/// Configuration for connecting to the Velocity Router.
#[derive(Debug, Clone)]
pub struct VelocityConfig {
    pub base_url: String,
    pub api_key: String,
}

impl VelocityConfig {
    /// Load from environment variables or config file.
    /// Checks VELOCITY_BASE_URL and VELOCITY_API_KEY env vars first,
    /// then falls back to ~/.velocity/config.toml.
    pub fn load() -> Result<Self> {
        // Try environment variables first.
        if let (Ok(url), Ok(key)) = (
            std::env::var("VELOCITY_BASE_URL"),
            std::env::var("VELOCITY_API_KEY"),
        ) {
            return Ok(Self {
                base_url: url,
                api_key: key,
            });
        }

        // Try ~/.velocity/config.toml with proper TOML parsing.
        if let Some(home) = dirs_next() {
            let config_path = home.join(".velocity").join("config.toml");
            if config_path.exists() {
                let content = std::fs::read_to_string(&config_path)
                    .context("failed to read ~/.velocity/config.toml")?;
                let parsed = parse_toml_simple(&content);
                if let (Some(url), Some(key)) = (
                    parsed.get("base_url").cloned(),
                    parsed.get("api_key").cloned(),
                ) {
                    return Ok(Self {
                        base_url: url,
                        api_key: key,
                    });
                }
            }
        }

        anyhow::bail!(
            "Velocity Router not configured.\n\
             Set VELOCITY_BASE_URL and VELOCITY_API_KEY environment variables,\n\
             or create ~/.velocity/config.toml with:\n\
             \n\
             base_url = \"http://localhost:8787\"\n\
             api_key = \"vr_standard_your_key_here\""
        )
    }

    /// Save configuration to ~/.velocity/config.toml.
    pub fn save(&self) -> Result<()> {
        if let Some(home) = dirs_next() {
            let config_dir = home.join(".velocity");
            std::fs::create_dir_all(&config_dir)
                .context("failed to create ~/.velocity directory")?;
            let config_path = config_dir.join("config.toml");
            let content = format!(
                "# Velocity Router configuration\n\
                 # Generated by velocity-ide login\n\
                 \n\
                 base_url = \"{}\"\n\
                 api_key = \"{}\"\n",
                self.base_url, self.api_key
            );
            std::fs::write(&config_path, content)
                .context("failed to write ~/.velocity/config.toml")?;
            Ok(())
        } else {
            anyhow::bail!("cannot determine home directory")
        }
    }
}

/// Minimal TOML key-value parser (handles simple `key = "value"` lines).
/// Skips comments, blank lines, section headers, and lines within sections.
/// Avoids pulling in the `toml` crate for this single use case.
fn parse_toml_simple(content: &str) -> HashMap<String, String> {
    let mut map = HashMap::new();
    let mut in_section = false;
    for line in content.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        // Section header — stop parsing top-level keys until next blank line.
        if line.starts_with('[') {
            in_section = true;
            continue;
        }
        // A new top-level key resets section tracking.
        if in_section {
            // Lines within a section are skipped.
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            let key = key.trim().to_string();
            let value = value.trim().trim_matches('"').to_string();
            map.insert(key, value);
        }
    }
    map
}

/// Simple home directory lookup without adding a dependency.
fn dirs_next() -> Option<std::path::PathBuf> {
    std::env::var_os("USERPROFILE")
        .or_else(|| std::env::var_os("HOME"))
        .map(std::path::PathBuf::from)
}

